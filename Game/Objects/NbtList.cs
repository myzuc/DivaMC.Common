using System.Collections;
using DivaMC.Common.IO.Serialization;
using fNbt;

namespace DivaMC.Common.Game.Objects
{
    public sealed class NbtList<T> : INbtSerializable<NbtList<T>>, IList<T> where T : INbtSerializable<T>
    {
        private readonly List<T> List;
        public NbtList()
        {
            List = [];
        }
        public NbtList(List<T> list)
        {
            List = list;
        }
        public NbtTag ToNbt()
        {
            return NbtList.FromIEnumerable(List.Select(entry => entry.ToNbt()));
        }
        public static NbtList<T> FromNbt(NbtTag nbt)
        {
            if (nbt is not NbtList nbtList)
            {
                return new([T.FromNbt(nbt)]);
            }
            return new(nbtList.Select(T.FromNbt).ToList());
        }
        
        //generated by rider:
        public IEnumerator<T> GetEnumerator()
        {
            return List.GetEnumerator();
        }
        IEnumerator IEnumerable.GetEnumerator()
        {
            return ((IEnumerable)List).GetEnumerator();
        }
        public void Add(T item)
        {
            List.Add(item);
        }
        public void Clear()
        {
            List.Clear();
        }
        public bool Contains(T item)
        {
            return List.Contains(item);
        }
        public void CopyTo(T[] array, int arrayIndex)
        {
            List.CopyTo(array, arrayIndex);
        }
        public bool Remove(T item)
        {
            return List.Remove(item);
        }
        public int Count
        {
            get
            {
                return List.Count;
            }
        }
        public bool IsReadOnly
        {
            get
            {
                return false;
            }
        }
        public int IndexOf(T item)
        {
            return List.IndexOf(item);
        }
        public void Insert(int index, T item)
        {
            List.Insert(index, item);
        }
        public void RemoveAt(int index)
        {
            List.RemoveAt(index);
        }
        public T this[int index]
        {
            get
            {
                return List[index];
            }
            set
            {
                List[index] = value;
            }
        }
    }
}